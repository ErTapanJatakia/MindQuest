import { createServer } from "node:http";
import { readFile } from "node:fs/promises";
import { extname, resolve, sep } from "node:path";
import { chromium } from "playwright";

const root = resolve("app");
const mime = { ".html":"text/html; charset=utf-8", ".css":"text/css; charset=utf-8", ".js":"text/javascript; charset=utf-8", ".svg":"image/svg+xml" };
const server = createServer(async (request, response) => {
  try {
    const pathname = decodeURIComponent(new URL(request.url, "http://127.0.0.1").pathname);
    const file = resolve(root, pathname === "/" ? "index.html" : pathname.slice(1));
    if (file !== root && !file.startsWith(root + sep)) return response.writeHead(403).end("Forbidden");
    response.writeHead(200, { "content-type": mime[extname(file)] || "application/octet-stream" });
    response.end(await readFile(file));
  } catch { response.writeHead(404).end("Not found"); }
});

let browser;
try {
  await new Promise((resolveListen, reject) => {
    server.once("error", reject);
    server.listen(4177, "127.0.0.1", resolveListen);
  });
  browser = await chromium.launch({ headless:true });
  const page = await browser.newPage();
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("http://127.0.0.1:4177/", { waitUntil:"networkidle" });

  const tagline = await page.locator(".splash-tagline span").allTextContents();
  if (tagline.join("|") !== "Stay Curious|Outsmart the Ordinary") throw new Error("Launch tagline must use two separate lines");
  if (!(await page.locator(".splash-wcag-badge img").isVisible())) throw new Error("Official launch WCAG logo is missing");
  if (await page.locator(".splash-tagline").evaluate(node => parseFloat(getComputedStyle(node).fontSize)) < 19.6) throw new Error("Launch tagline size increase is missing");
  // The launch dialog traps keyboard focus and the app remains inert until dismissed.
  if (!(await page.locator(".app-shell").evaluate(node => node.inert && node.getAttribute("aria-hidden")==="true"))) {
    throw new Error("Launch dialog did not isolate the application from assistive technology");
  }
  await page.keyboard.press("Tab");
  if (await page.evaluate(() => document.activeElement?.classList.contains("splash-wcag-badge")) !== true) {
    throw new Error("Launch WCAG logo link is not keyboard reachable");
  }
  await page.keyboard.press("Tab");
  if (await page.evaluate(() => document.activeElement?.id) !== "splash-dismiss") {
    throw new Error("Launch dialog focus loop does not include the WCAG logo link");
  }
  await page.keyboard.press("Escape");
  await page.locator("#launch-splash").waitFor({ state:"detached" });
  if (await page.evaluate(() => document.activeElement?.id) !== "home-title") {
    throw new Error("Dismissed launch dialog did not return focus to the Home heading");
  }

  await page.locator("#privacy-link").click();
  const privacyText = await page.locator("#privacy-view").innerText();
  for (const marker of ["1. Overview","2. Information handled by the application","3. Network access and third parties","4. Children and families","5. Data retention and security","6. Your choices and rights","7. Changes to this policy","8. Contact information","Data Protection Officer (DPO)"]) if (!privacyText.includes(marker)) throw new Error("Privacy policy missing section: " + marker);
  await page.locator("#privacy-back").click();
  await page.locator("#accessibility-link").click();
  const accessibilityText = await page.locator("#accessibility-view").innerText();
  for (const marker of ["Commitment","Standards and conformance responsibility","Accessibility features and design practices","Known limitations and verification","Feedback and remediation","Accessibility feedback contact"]) if (!accessibilityText.includes(marker)) throw new Error("Accessibility statement missing section: " + marker);
  if (await page.locator("#accessibility-view .wcag-logo-link").count() !== 2) throw new Error("Official W3C WCAG logos must appear at top and bottom");
  if (privacyText.includes("For the complete policy, see") || accessibilityText.includes("For the complete statement, see")) throw new Error("Legal view still defers its full document to the repository");
  if (!privacyText.includes("How MindQuest Handles Your Data?")) throw new Error("Privacy heading must include the exact requested question mark");
  if (privacyText.includes("not legal advice")) throw new Error("Privacy policy retains the unwanted editorial disclaimer");
  const visibleCopy = await page.locator("body").innerText();
  if (/\\b(?:AI[- ]generated|generated by (?:an? )?AI|created by (?:ChatGPT|OpenAI)|machine[- ]generated)\\b/i.test(visibleCopy)) throw new Error("User-facing content contains an AI/machine authorship attribution");
  await page.locator("#accessibility-back").click();

  // View transitions must announce context by moving focus to the destination heading.
  for (const [trigger, heading, back] of [
    ["#settings-open", "settings-title", "#settings-back"],
    ["#home-help", "help-title", "#help-back"],
    ["#privacy-link", "privacy-title", "#privacy-back"],
    ["#accessibility-link", "accessibility-title", "#accessibility-back"]
  ]) {
    await page.locator(trigger).click();
    if (await page.evaluate(() => document.activeElement?.id) !== heading) {
      throw new Error("View transition did not focus its heading: " + heading);
    }
    await page.locator(back).click();
    if (await page.evaluate(() => document.activeElement?.id) !== "home-title") {
      throw new Error("Back navigation did not restore Home context after " + heading);
    }
  }

  // All accessibility controls must apply their preference and persist it across reload.
  await page.locator("#settings-open").click();
  const introText = await page.locator(".settings-intro").innerText();
  if (introText !== "Choose each setting independently: Interface Language, Question Region, Question Language, Category, Difficulty.") throw new Error("Settings intro copy is incorrect");
  if (await page.locator("#settings-save").innerText() !== "Save Settings") throw new Error("Save Settings button copy is incorrect");
  for (const label of ["Larger Text","Reduce Motion","High Contrast"]) if (!(await page.locator(".accessibility-settings").innerText()).includes(label)) throw new Error("Accessibility label missing: " + label);
  const settingsHeading = await page.locator("#settings-title").getAttribute("tabindex");
  if (settingsHeading !== "-1") throw new Error("Settings heading is not programmatically focusable");
  for (const selector of ["#interface-locale","#question-region","#question-locale","#question-category","#theme-select"]) {
    if (!(await page.locator(selector).isVisible())) throw new Error("Native setting selector is not visible: " + selector);
    const id = selector.slice(1);
    if (!(await page.locator("label[for=\x27" + id + "\x27]").count())) throw new Error("Setting selector lacks an associated label: " + selector);
  }
  const interfaceOptions = await page.locator("#interface-locale option").evaluateAll(nodes => nodes.map(node => node.value));
  const questionOptions = await page.locator("#question-locale option").evaluateAll(nodes => nodes.map(node => node.value));
  const expectedLocales = ["en-IN","en-US","ru-RU","es-PE","es-ES"];
  if (expectedLocales.some(locale => !interfaceOptions.includes(locale) || !questionOptions.includes(locale))) throw new Error("Complete five-locale catalogue is not exposed");
  if (await page.locator("#theme-open").count()) throw new Error("Header colour-theme icon must not be present");
  await page.locator("#settings-back").click();
  await page.locator("#settings-open").click();
  await page.locator("#setting-large-text").check();
  await page.locator("#setting-reduced-motion").check();
  await page.locator("#setting-high-contrast").check();
  const applied = await page.evaluate(() => ({
    large:document.documentElement.classList.contains("large-text"),
    reduced:document.documentElement.classList.contains("user-reduced-motion"),
    contrast:document.documentElement.classList.contains("user-high-contrast")
  }));
  if (!applied.large || !applied.reduced || !applied.contrast) {
    throw new Error("Accessibility preferences did not apply their corresponding document modes");
  }
  const motionDuration = await page.locator("#settings-view").evaluate(node => getComputedStyle(node).transitionDuration);
  if (!motionDuration.split(",").every(value => parseFloat(value) <= 0.011)) {
    throw new Error("Reduced-motion preference did not suppress transitions: " + motionDuration);
  }
  await page.locator("#settings-back").click();
  await page.reload({ waitUntil:"networkidle" });
  await page.locator("#splash-dismiss").click();
  const persisted = await page.evaluate(() => ({
    large:document.documentElement.classList.contains("large-text"),
    reduced:document.documentElement.classList.contains("user-reduced-motion"),
    contrast:document.documentElement.classList.contains("user-high-contrast")
  }));
  if (!persisted.large || !persisted.reduced || !persisted.contrast) {
    throw new Error("Accessibility preferences did not survive application reload");
  }

  // Theme selection is a native keyboard-operable Settings control.
  await page.locator("#settings-open").click();
  await page.locator("#theme-select").focus();
  if (await page.evaluate(() => document.activeElement?.id) !== "theme-select") throw new Error("Theme selector cannot receive keyboard focus");
  await page.locator("#theme-select").selectOption("paper");
  await page.locator("#settings-back").click();
  await page.reload({ waitUntil:"networkidle" });
  await page.locator("#splash-dismiss").click();
  if (await page.locator("html").getAttribute("data-theme") !== "paper") {
    throw new Error("Selected theme did not survive reload");
  }

  // Forced-colors and OS reduced-motion media preferences must retain usable controls.
  await page.emulateMedia({ forcedColors:"active", reducedMotion:"reduce" });
  await page.locator("#settings-open").click();
  const forced = await page.locator("#theme-select").evaluate(node => {
    const style = getComputedStyle(node);
    return { outlineStyle:style.outlineStyle, outlineWidth:style.outlineWidth, display:style.display };
  });
  if (forced.display === "none") throw new Error("Theme control disappeared in forced-colors mode");
  await page.locator("#settings-back").click();
  const splashForced = await page.locator(".app-shell").evaluate(node => {
    const style = getComputedStyle(document.querySelector(".app-shell"));
    return { visibility:style.visibility, display:style.display };
  });
  if (splashForced.display === "none" || splashForced.visibility === "hidden") {
    throw new Error("Application content became unavailable in forced-colors mode");
  }

  // Verify one-question keyboard radio movement selects and focuses the next option.
  await page.emulateMedia({ forcedColors:"none", reducedMotion:"no-preference" });
  await page.locator("#play-button").click();
  if (await page.evaluate(() => document.activeElement?.id) !== "question-title") {
    throw new Error("Starting a round did not focus the question heading");
  }
  const first = page.locator("#answers button[role=radio]").first();
  await first.focus();
  await page.keyboard.press("ArrowRight");
  if (await page.locator('#answers button[role=radio][aria-checked="true"]').count() !== 1) {
    throw new Error("Arrow navigation did not select exactly one answer");
  }
  if (await page.evaluate(() => document.activeElement?.id) !== "next-button") {
    throw new Error("Keyboard answer selection did not move focus to the Next action");
  }
  // Large-text, high-contrast and reduced-motion preferences must remain usable together on a compact viewport.
  await page.setViewportSize({ width:320, height:720 });
  await page.reload({ waitUntil:"networkidle" });
  await page.locator("#splash-dismiss").click();
  const largeTextRootSize = await page.evaluate(() => Number.parseFloat(getComputedStyle(document.documentElement).fontSize));
  if (!(largeTextRootSize > 16)) {
    throw new Error("Large-text preference did not increase the root text scale: " + largeTextRootSize);
  }
  async function assertCompactReflow(label) {
    const layout = await page.evaluate(() => {
      const width = document.documentElement.clientWidth;
      const visible = [...document.querySelectorAll("button,a[href],input:not([type='hidden']),select,textarea,[role='radio']")]
        .filter(node => node.getClientRects().length && getComputedStyle(node).visibility !== "hidden" &&
          !node.closest("[hidden],[aria-hidden='true'],[inert]"));
      return {
        width,
        documentWidth:document.documentElement.scrollWidth,
        bodyWidth:document.body.scrollWidth,
        escaped:visible.map(node => {
          const rect=node.getBoundingClientRect();
          return { id:node.id || node.tagName.toLowerCase(), left:rect.left, right:rect.right };
        }).filter(rect => rect.left < -1 || rect.right > width + 1)
      };
    });
    if (layout.documentWidth > layout.width || layout.bodyWidth > layout.width || layout.escaped.length) {
      throw new Error(label + " reflow failed at 320 CSS px with large text/high contrast: " + JSON.stringify(layout));
    }
  }
  await assertCompactReflow("Home");
  await page.locator("#settings-open").click();
  await assertCompactReflow("Settings");
  await page.locator("#settings-back").click();
  await page.locator("#play-button").click();
  await assertCompactReflow("Quiz");
  const compactRoundLength = Number(await page.locator("#round-length").inputValue().catch(() => "10"));
  const compactQuestions = Number.isFinite(compactRoundLength) && compactRoundLength > 0 ? compactRoundLength : 10;
  for (let index=0; index<compactQuestions; index+=1) {
    const answers = page.locator("#answers button[role=radio]");
    if (!(await answers.count())) throw new Error("Compact large-text quiz lost answer controls at question " + (index + 1));
    await answers.first().click();
    await page.locator("#next-button").waitFor({ state:"visible" });
    await page.locator("#next-button").click();
  }
  await page.locator("#result-view.active").waitFor({ state:"visible" });
  await assertCompactReflow("Results and answer review");

  if (errors.length) throw new Error("Browser runtime errors: " + errors.join(" | "));
  console.log("Accessibility regression passed: modal launch focus isolation, native locale/settings selectors, embedded legal disclosures, official linked W3C WCAG logos, accessibility preferences, Settings theme selection, forced-colors availability, and arrow-key radio navigation.");
} finally {
  await browser?.close();
  await new Promise(resolveClose => server.close(resolveClose));
}
